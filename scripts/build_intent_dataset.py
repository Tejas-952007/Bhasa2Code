def build_dataset() -> List[Dict]:
    """Compile dataset into a list of normalized dictionary rows."""
    dataset = []
    seen_texts = set()
    current_id = 1

    for intent, lang_dict in INTENT_DATA.items():
        for lang, samples in lang_dict.items():
            for text in samples:
                clean_text = text.strip()
                if clean_text in seen_texts:
                    raise ValueError(f"Duplicate sample detected: '{clean_text}'")
                seen_texts.add(clean_text)

                dataset.append(
                    {
                        "id": current_id,
                        "text": clean_text,
                        "intent": intent,
                        "language": lang,
                        "domain": "coding",
                    }
                )
                current_id += 1

    return dataset


def split_dataset(
    dataset: List[Dict],
    train_ratio: float = 0.70,
    val_ratio: float = 0.15,
) -> Dict[str, List[Dict]]:
    """Deterministically stratify dataset by intent label."""
    rng = random.Random(RANDOM_SEED)

    by_intent: Dict[str, List[Dict]] = {}
    for item in dataset:
        by_intent.setdefault(item["intent"], []).append(item)

    train_set: List[Dict] = []
    val_set: List[Dict] = []
    test_set: List[Dict] = []

    for intent, items in sorted(by_intent.items()):
        shuffled = list(items)
        rng.shuffle(shuffled)

        n = len(shuffled)
        n_train = int(round(n * train_ratio))  # 60 * 0.70 = 42
        n_val = int(round(n * val_ratio))      # 60 * 0.15 = 9
        # remainder for test: 60 - 42 - 9 = 9

        train_chunk = shuffled[:n_train]
        val_chunk = shuffled[n_train : n_train + n_val]
        test_chunk = shuffled[n_train + n_val :]

        train_set.extend(train_chunk)
        val_set.extend(val_chunk)
        test_set.extend(test_chunk)

    train_set.sort(key=lambda x: x["id"])
    val_set.sort(key=lambda x: x["id"])
    test_set.sort(key=lambda x: x["id"])

    return {"train": train_set, "validation": val_set, "test": test_set}


def write_csv(filepath: str, rows: List[Dict]) -> None:
    """Write list of row dicts to CSV."""
    with open(filepath, "w", newline="", encoding="utf-8") as f:
        writer = csv.DictWriter(
            f, fieldnames=["id", "text", "intent", "language", "domain"]
        )
        writer.writeheader()
        writer.writerows(rows)


def write_jsonl(filepath: str, rows: List[Dict]) -> None:
    """Write list of row dicts to JSONL."""
    with open(filepath, "w", encoding="utf-8") as f:
        for row in rows:
            f.write(json.dumps(row, ensure_ascii=False) + "\n")


def main() -> None:
    os.makedirs(DATASET_DIR, exist_ok=True)

    dataset = build_dataset()
    print(f"Compiled {len(dataset)} unique intent samples.")

    # Write complete dataset
    full_csv = os.path.join(DATASET_DIR, "intent_dataset.csv")
    full_jsonl = os.path.join(DATASET_DIR, "intent_dataset.jsonl")
    write_csv(full_csv, dataset)
    write_jsonl(full_jsonl, dataset)
    print(f"Wrote full dataset to {full_csv} and {full_jsonl}")

    # Generate splits
    splits = split_dataset(dataset)
    for split_name, split_rows in splits.items():
        split_csv = os.path.join(DATASET_DIR, f"intent_{split_name}.csv")
        write_csv(split_csv, split_rows)
        print(f"Wrote {len(split_rows)} samples to {split_csv}")


if __name__ == "__main__":
    main()
